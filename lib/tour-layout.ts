/**
 * Ширина контентного блока на странице тура — ОДНО место на всю страницу.
 *
 * Было `max-w-4xl` (896px) в каждом блоке по отдельности: на экране 1920 контент
 * занимал 47% ширины, и заказчик 2026-08-21 сказал «все блоки слишком узкие».
 * Просто заменить на `max-w-6xl` (1152px) нельзя — см. вычитание ниже.
 *
 * `100vw - 11rem` — это место под стрелки каруселей. В «Что нас ждёт» и
 * «Размещении» стрелки вынесены ЗА контентную область: круг 56px плюс отступ
 * 24px, то есть по 80px с каждой стороны, и они живут в полях страницы, а не
 * в контейнере. Пока блок был 896px, поля на широком экране это скрывали, но
 * на 1280 и уже стрелки начинали свисать за край экрана — на 1024 это было
 * так и ДО расширения (896 + 160 = 1056 > 1024), просто никто не замерял.
 * Вычитание 176px (2×80 плюс запас) держит стрелки на экране на любой ширине.
 *
 * `min()` берёт меньшее: на 1920 работает потолок 72rem (1152px), на узких
 * экранах — вычитание. Побочный эффект приятный: все блоки страницы получают
 * одинаковую ширину на любом экране, чего раньше не было (карусели шли по
 * 896px, а секции-обёртки по 1216px).
 *
 * Сплошной текст этой ширины НЕ использует — «О туре» и текстовое описание
 * цены намеренно остаются `max-w-4xl`: строка в 1152px при кегле 20px это
 * ~150 знаков, читать такое неудобно.
 *
 * ⚠️ ВЫЧИТАНИЕ ТОЛЬКО С `md` (2026-08-25). Место под стрелки нужно ровно там,
 * где стрелки есть, а они `hidden md:flex` в обеих каруселях
 * (`program-days-carousel.tsx`, `accommodation-carousel.tsx`) — ниже 768px их
 * нет вообще. Пока вычитание было безусловным, на телефоне оно съедало
 * фиксированные 176px из 390: контентный блок получался **214px, то есть 55%
 * экрана, с пустыми полями по 88px с каждой стороны** (замер на iPhone-ширине
 * 390px). Заказчик это и увидел — «на мобильном всё слишком ужалось».
 *
 * Чем уже экран, тем больнее: 176px — это 45% от 390, но всего 14% от 1280.
 * Поэтому фиксированное вычитание из `100vw` на мобильных вообще неприменимо.
 * Ниже `md` блок просто занимает ширину контейнера (`Container` уже даёт свои
 * поля `px-4`), `max-w-full` тут — страховка от переполнения, а не ограничение.
 *
 * ⚠️ С `lg` (11.09.2026) — ВСЯ ширина контейнера, как на главной: страница тура
 * живёт по тому же закону одного множителя (контейнер 1053 × `--ona-u`, поля
 * по 113.5 при 1280), и стрелки каруселей (круг 44.8 + отступ 19.2 = 64 ×
 * `--ona-u`) помещаются в поля страницы на любой ширине `lg` сами собой.
 */
export const TOUR_BLOCK_WIDTH = "max-w-full md:max-w-[min(72rem,100vw-11rem)] lg:max-w-none";

/**
 * Ширина «обложки» тура — главного фото и строки «Даты / Стоимость» над ним.
 *
 * На фото название тура и даты ВПЕЧАТАНЫ в сам снимок (это не вёрстка), поэтому
 * они уменьшаются только вместе с фото. Когда 11.09 страница перешла на шкалу
 * главной, текст вокруг стал на 20–35 % мельче, а фото во всю ширину блока
 * осталось почти прежним (1053 против 1104 при 1280) — оно и надписи на нём
 * «выпирали» (замечание Ильи). Обложке — то же облегчение × 0.8, что всему
 * туру: 1104 × 0.8 = 883.2 при 1280 × `--ona-u`, по центру.
 * Идёт ПОСЛЕ `TOUR_BLOCK_WIDTH` в `cn()` — перебивает его `lg:max-w-none`.
 */
export const TOUR_COVER_WIDTH = "lg:max-w-[calc(883.2*var(--ona-u))]";
