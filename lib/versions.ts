export type VersionStatus = "ready" | "draft" | "archived";

export interface VersionMeta {
  /** Часть URL: /versions/<id>. Латиница, цифры и дефис. */
  id: string;
  /** Короткое имя для кнопки и плашки наверху страницы. */
  title: string;
  /** 1–2 предложения для заказчика: чем эта версия отличается. */
  description: string;
  /**
   * `ready` — показываем заказчику;
   * `draft` — в работе, на хабе помечена и вынесена вниз;
   * `archived` — на хабе не показывается, но ссылка продолжает работать.
   */
  status: VersionStatus;
}

