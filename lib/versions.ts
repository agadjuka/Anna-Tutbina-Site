export function getVersion(id: string): VersionMeta | undefined {
  return VERSIONS.find((v) => v.id === id);
}

/** Версии для показа на хабе: `ready` сначала, `draft` следом, `archived` скрыты. */
export function getVisibleVersions(): VersionMeta[] {
  const order: Record<VersionStatus, number> = { ready: 0, draft: 1, archived: 2 };
  return VERSIONS.filter((v) => v.status !== "archived").sort(
    (a, b) => order[a.status] - order[b.status]
  );
}
