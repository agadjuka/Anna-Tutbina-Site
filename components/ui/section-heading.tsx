import { cn } from "@/lib/utils";

interface SectionHeadingProps {
  children: React.ReactNode;
  className?: string;
  as?: "h1" | "h2" | "h3";
  variant?: "default" | "light";
}

export function SectionHeading({ 
  children, 
  className,
  as: Component = "h2",
  variant = "default"
}: SectionHeadingProps) {
  const textColor =
    variant === "light" ? "text-white/90" : "text-primary";

  const lineColor = variant === "light" ? "bg-white/30" : "bg-primary";

  return (
    <div className={cn("w-full flex justify-center", className)}>
      {/* Волосяные линии — во всю оставшуюся ширину (`flex-1`), как и было
          до Н9: заказчик попросил вернуть именно такую подачу.

          Строка заголовка занимает ВСЮ ширину секции (1216px при 1920), своего
          `max-w` у неё нет. Промежуточный вариант с потолком в 62% заказчик
          забраковал сразу — «как-то узко стало всё позиционироваться»: длинные
          заголовки складывались в узкий столбик по центру широкой секции.

          Вместо потолка ширины — потолок КЕГЛЯ: 36px при 1920. Сначала было
          ровно как на главной (50px), потом 45px — заказчик оба раза попросил
          мельче. 36px против прежних 24px всё равно в полтора раза крупнее и
          снимает главное расхождение с главной; при этом самый длинный
          заголовок («ЧТО ГОВОРЯТ НАШИ УЧАСТНИЦЫ») помещается в одну строку и
          линиям остаётся почти по 290px с каждой стороны (на 45px оставалось
          по 51px, на 50px — по 10px, и они читались как чёрточки). */}
      <div className="flex w-full items-center gap-4 md:gap-6">
        <div className={cn("h-px min-w-[10vw] flex-1 md:min-w-0", lineColor)} />
        <Component
          className={cn(
            /* Кегль и трекинг — из системы главной (задача Н9): Cormorant
               обычного начертания, капсом, БЕЗ межбуквенного интервала, размер
               доходит до 50px при 1920 — ровно как у H2 блоков REVIEWS, COLLAB
               и FAQ. Было 24px с трекингом 0.2em: заголовки страницы тура были
               вдвое мельче заголовков главной и единственные на сайте набирались
               «вразрядку», из-за чего страница читалась как чужая.

               `whitespace-nowrap` снят намеренно: на прежних 24px длинные
               заголовки («ЧТО ГОВОРЯТ НАШИ УЧАСТНИЦЫ») помещались в строку, на
               50px — уже нет, и запрет переноса вытолкнул бы их за контейнер.
               Волосяные линии по бокам остаются — это приём страницы тура,
               заказчик просил выровнять типографику, а не убрать оформление. */
            "font-heading font-normal uppercase text-center leading-tight break-normal whitespace-normal hyphens-none",
            "text-[22px] sm:text-[26px] lg:text-[clamp(26px,1.875vw,36px)]",
            /* Потолок ширины — только с `lg`. Он заставляет два самых длинных
               заголовка перенестись на две строки, и разброс длины линий
               сжимается с 125–524px до ~300–520px (решение заказчика:
               «длинные заголовки в две строки»). Ниже `lg` потолок вреден —
               на телефоне строка и так узкая, заголовок сложился бы в столбик. */
            "lg:max-w-[46%]",
            textColor
          )}
        >
          {children}
        </Component>
        <div className={cn("h-px min-w-[10vw] flex-1 md:min-w-0", lineColor)} />
      </div>
    </div>
  );
}
