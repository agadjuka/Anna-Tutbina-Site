import { cn } from "@/lib/utils";

interface SectionEyebrowProps {
  children: React.ReactNode;
  /** Цвет и выравнивание — они у блоков разные (тёмная заливка / светлый фон). */
  className?: string;
}

/**
 * Надзаголовок блока — мелкая строка капсом над H2 («О ПРОЕКТЕ», «КАЛЕНДАРЬ»,
 * «НАШИ ЦЕННОСТИ»).
 *
 * Зачем примитив. Раньше эти строки набирались классами прямо в каждой секции,
 * и к августу 2026 они разъехались на два размера: 15px в HERO, CALENDAR,
 * VALUES, GUESTS, REVIEWS и FAQ — и 13px в ABOUT, FOUNDERS и COLLAB (задача Н10
 * в `docs/redesign/backlog.md`). На глаз разница читается как «блоки набраны
 * по-разному», хотя роль у строки везде одна.
 *
 * Здесь размер задан ОДИН раз: 13px на телефоне, 15px от `sm` и выше. Это
 * поведение большинства блоков до сведения; 15px — то значение, что снято
 * с узла Figma `5:156` (CALENDAR).
 *
 * Через `className` передаются только цвет и выравнивание: кегль, насыщенность,
 * регистр и трекинг — общие, и переопределять их не нужно. Если в новом блоке
 * захотелось другой кегль — скорее всего, это не надзаголовок блока, а что-то
 * другое (как подпись роли «ОСНОВАТЕЛЬ» в диптихе FOUNDERS: она мельче
 * намеренно и этот примитив не использует).
 */
export function SectionEyebrow({ children, className }: SectionEyebrowProps) {
  return (
    /* От `lg` кегль пропорционален ширине окна (15px на 1920, формула
       15/1920 = 0.78vw) с полом читаемости 12px — часть общего закона
       масштабирования главной (2026-08-21): при сужении окна ужимается
       ВСЁ, включая надзаголовки, а не только заголовки рядом с ними. */
    <p className={cn("text-[13px] font-medium uppercase tracking-[0.18em] sm:text-[15px] lg:text-[clamp(12px,0.78vw,15px)]", className)}>
      {children}
    </p>
  );
}
