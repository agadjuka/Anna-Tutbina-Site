"use client";

import { useEffect } from "react";

/**
 * Принудительно включает анимации на страницах сравнения версий (`/versions/*`),
 * даже если в ОС/браузере включена системная настройка «уменьшить анимацию».
 *
 * Почему это здесь нужно, а на боевом сайте — нет: `/versions` существует для
 * того, чтобы заказчик увидел и оценил анимацию и принял решение. Если её на
 * этой странице приглушать под системную настройку — там просто нечего будет
 * оценивать (так и произошло: с этой настройкой на устройстве заказчика ни
 * дыхание круга в футере, ни очередное появление карточек не было видно, хотя
 * оба реализованы и работают — проверено инструментально). На самом сайте
 * (`/`, боевая версия) `prefers-reduced-motion` по-прежнему соблюдается как
 * положено — этот компонент подключён только в `/versions/[id]`.
 *
 * Механизм: ставит атрибут на `<html>`, а `app/globals.css` при его наличии
 * форсирует анимацию обратно (см. правила `html[data-force-motion="true"]`),
 * перекрывая `@media (prefers-reduced-motion: reduce)`.
 */
export function ForceMotion() {
  useEffect(() => {
    document.documentElement.setAttribute("data-force-motion", "true");
    return () => {
      document.documentElement.removeAttribute("data-force-motion");
    };
  }, []);

  return null;
}
